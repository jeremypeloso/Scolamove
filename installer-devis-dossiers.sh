#!/usr/bin/env bash
# =============================================================================
# Scolamove : installation du module « Devis et dossiers de voyage »
#
# À lancer depuis la racine du dépôt Scolamove (Git Bash sous Windows) :
#     bash installer-devis-dossiers.sh
#
# Le script :
#   1. copie les nouveaux fichiers (lib/voyage, components/voyage,
#      app/admin/voyages, supabase/migrations) ;
#   2. ajoute le lien « Devis et dossiers » au menu du tableau de bord, sans
#      remplacer le fichier app/admin/page.tsx ;
#   3. propose de pousser sur GitHub et de déployer sur Vercel.
#
# Il ne touche pas à la base : le fichier SQL reste à exécuter dans Supabase.
# =============================================================================
set -euo pipefail

if [ ! -f package.json ] || [ ! -d app/admin ] || ! grep -q '"scolamove-site"' package.json; then
  echo "Ce dossier n'est pas la racine du dépôt Scolamove."
  echo "Place-toi dans le dépôt (là où se trouve package.json), puis relance."
  exit 1
fi

echo "1/3  Copie des fichiers…"
sed '1,/^__PAQUET__$/d' "$0" | base64 --decode | tar -xzf -
echo "     $(find lib/voyage components/voyage app/admin/voyages supabase/migrations -type f | wc -l | tr -d ' ') fichiers en place."

echo "2/3  Menu du tableau de bord…"
MENU=app/admin/page.tsx
if grep -q '/admin/voyages' "$MENU"; then
  echo "     Lien déjà présent."
elif grep -q 'href="/admin/devis-express" className="admin-menu-link"' "$MENU"; then
  perl -0pi -e 's{<a href="/admin/devis-express" className="admin-menu-link">\s*Devis Express\s*</a>}{<a href="/admin/voyages" className="admin-menu-link">\n            Devis et dossiers\n          </a>\n          <a href="/admin/devis-express" className="admin-menu-link">\n            Ancien devis express\n          </a>}' "$MENU"
  if grep -q '/admin/voyages' "$MENU"; then
    echo "     Lien « Devis et dossiers » ajouté, l'ancien écran devient « Ancien devis express »."
  else
    echo "     Lien non ajouté : le menu a changé. Le module reste accessible sur /admin/voyages."
  fi
else
  echo "     Menu introuvable dans $MENU. Le module reste accessible sur /admin/voyages."
fi

echo "3/3  Mise en ligne"
printf "     Pousser sur GitHub et déployer sur Vercel maintenant ? [o/N] "
read -r REPONSE || REPONSE=""
if [ "$REPONSE" = "o" ] || [ "$REPONSE" = "O" ]; then
  git add -A && git commit -m "Devis et dossiers de voyage : cotation, réservations et feuille de route reliés" && git push
  vercel --prod
else
  echo "     Rien n'a été poussé."
fi

echo
echo "Il reste deux choses à faire à la main :"
echo "  - exécuter supabase/migrations/20261002_dossiers_voyage.sql dans Supabase (SQL Editor) ;"
echo "  - compléter lib/voyage/agence.ts (immatriculation, garant, assureur, permanence)."
exit 0
